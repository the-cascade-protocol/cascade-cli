/** One kind of wellness record the view reads, as the rule table states it. */
export interface ReadingTypeRule {
  /** Full IRI of the record class. */
  classIri: string;
  /** A fixed key, or (`keyFrom`) the predicate whose value's local name is the key. */
  key?: string;
  keyFrom?: string;
  /** Predicate carrying the number (series types only). */
  value?: string;
  /** A fixed unit, or the predicate carrying it. */
  unit?: string;
  unitFrom?: string;
  /** Predicate carrying the instant whose local date is the record's day. */
  day: string;
  /** True when the type has a daily series; false when it is only summarised. */
  series: boolean;
}

export interface TierRule {
  label: string;
  manufacturer: RegExp;
  hardware: RegExp;
  nameWhenUnstated: RegExp;
}

export interface DailySeriesRules {
  rule: string;
  ruleVersion: string;
  /** Pod data-type keys whose files the view is built from, in the table's order. */
  inputs: string[];
  tiers: TierRule[];
  otherTier: string;
  readingTypes: ReadingTypeRule[];
}

function expand(curie: string): string {
  const i = curie.indexOf(':');
  const ns = i > 0 ? PREFIXES[curie.slice(0, i)] : undefined;
  if (!ns) throw new Error(`wellness daily series rules: unknown prefix in "${curie}"`);
  return ns + curie.slice(i + 1);
}

let cachedRules: DailySeriesRules | undefined;

/** The rule table, read and checked once. Throws on a table this module cannot apply. */
export function dailySeriesRules(): DailySeriesRules {
  if (cachedRules) return cachedRules;
  const raw = seriesRulesAsset as unknown as {
    rule: string;
    ruleVersion: string;
    inputs: string[];
    tiers: Array<{ label: string; manufacturer: string; hardware: string; nameWhenUnstated: string }>;
    otherTier: string;
    patternFlags: string;
    readingTypes: Array<{
      class: string;
      key?: string;
      keyFrom?: string;
      value?: string;
      unit?: string;
      unitFrom?: string;
      day: string;
      series: boolean;
    }>;
  };
  const known = new Set(excludableDataFiles().map((e) => e.key));
  for (const key of raw.inputs) {
    if (!known.has(key)) throw new Error(`wellness daily series rules: unknown input data type "${key}"`);
  }
  const readingTypes = raw.readingTypes.map((t): ReadingTypeRule => {
    if ((t.key === undefined) === (t.keyFrom === undefined)) {
      throw new Error(`wellness daily series rules: ${t.class} needs exactly one of key and keyFrom`);
    }
    if (t.series && (t.value === undefined || (t.unit === undefined) === (t.unitFrom === undefined))) {
      throw new Error(`wellness daily series rules: series type ${t.class} needs a value and exactly one of unit and unitFrom`);
    }
    return {
      classIri: expand(t.class),
      key: t.key,
      keyFrom: t.keyFrom === undefined ? undefined : expand(t.keyFrom),
      value: t.value === undefined ? undefined : expand(t.value),
      unit: t.unit,
      unitFrom: t.unitFrom === undefined ? undefined : expand(t.unitFrom),
      day: expand(t.day),
      series: t.series,
    };
  });
  cachedRules = {
    rule: raw.rule,
    ruleVersion: raw.ruleVersion,
    inputs: raw.inputs,
    tiers: raw.tiers.map((t) => ({
      label: t.label,
      manufacturer: new RegExp(t.manufacturer, raw.patternFlags),
      hardware: new RegExp(t.hardware, raw.patternFlags),
      nameWhenUnstated: new RegExp(t.nameWhenUnstated, raw.patternFlags),
    })),
    otherTier: raw.otherTier,
    readingTypes,
  };
  return cachedRules;
}

/** The files the view is built from, by data-type key and pod-relative path, in the table's order. */
export function dailySeriesInputs(): Array<{ key: string; file: string }> {
  const files = new Map(excludableDataFiles().map((e) => [e.key, e.file]));
  return dailySeriesRules().inputs.map((key) => ({ key, file: files.get(key)! }));
}

/** Pod-relative paths of the files the view is built from, in the table's order. */
export function dailySeriesInputFiles(): string[] {
  return dailySeriesInputs().map((i) => i.file);
}

