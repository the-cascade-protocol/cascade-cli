/**
 * The stored daily wellness series: a compact DERIVED VIEW over a pod's
 * wellness records, so a reader can show a daily series and a per-source
 * summary without reading, decrypting and parsing tens of thousands of records.
 *
 * WHAT IT IS. For each reading type and statistic, one value per local day,
 * chosen by the source-priority read rule in
 * `src/data/wellness-daily-series-rules.json` (watch, then phone, then
 * third-party). Each day carries the chosen value, the source and device it
 * came from, the zone its day was cut in and the IRI of the daily record it was
 * taken from, so a reader cites the pod's own record and never this view. Plus
 * one summary row per source: its devices and, per reading type, the days it
 * covers and the first and last of them.
 *
 * WHY IT IS STORED. D-WELLNESS-1's amendment: a computed aggregate is a derived
 * view, stored when it pays, stamped with the version of its rule, and
 * rebuildable. This one pays: the records it summarises cost seconds and
 * gigabytes to read on every bind, and the view costs a few megabytes.
 *
 * WHAT IT IS NOT. Not a record and not layer 1: it names nothing, nothing
 * durable points at it, and deleting it loses nothing. The import writes one
 * record per (source, device, metric, statistic, day) and never picks a winner;
 * this view is where the reader's rule is applied, once, in one place.
 *
 * DETERMINISM. The view is a function of the records' triples, the pod's day
 * zone and the rule table, and nothing else: no clock, no file order, no run
 * value. Everything is sorted before it is written, so rebuilding it, or
 * deleting it and importing again, gives the same bytes.
 *
 * WHERE (provisional). The JSON bytes are a content-addressed attachment,
 * `attachments/sha-256/<digest>` (pod-structure.md section 4.3), sealed like
 * every other pod file on an encrypted pod. The descriptor,
 * `wellness/series/daily-series.ttl`, is a `cascade:Attachment` generated by an
 * activity stamped `cascade:version "wellness-daily-series/<ruleVersion>"`. The
 * series itself stays in the JSON: the bundled vocabulary has no terms for a
 * chosen-day row, and this CLI does not invent them.
 */

